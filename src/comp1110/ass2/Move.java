package comp1110.ass2;


/**
 * This class aims to deal with the movement about Assam(The customer).
 */
public class Move {

    private IntPair translation;
    private Direction direction;
    private final Die die;

    public enum Direction {
        UP, DOWN, RIGHT, LEFT
    }


    public Move(IntPair translation, Direction direction, Die die) {
        this.translation = translation;
        this.direction = direction;
        this.die = die;
    }



    /**
     * Applies the transformation to the customer based on the die roll.
     * Base on the direction of Assam, add the number of movement which is generated by the die to getX or y.
     * If direction is Up or Down, y + movement or y - movement.
     * If direction is Right or Left, getX + movement or y + movement.
     * If Assam hit the board edge, then turn left.(7 getX 7 board)
     * @return IntPair representing the new coordinates after applying the die effect
     */
    public IntPair applyTransform() {
        int dieEffect = die.getDieNumber();
        int newX = translation.getX();
        int newY = translation.getY();

        while (dieEffect > 0) {
            if (direction == Direction.UP) {
                newY += 1;
                if (newY > 6) {
                    newY = 6;
                    turnLeft();
                    continue;
                }
            } else if (direction == Direction.DOWN) {
                newY -= 1;
                if (newY < 0) {
                    newY = 0;
                    turnLeft();
                    continue;
                }
            } else if (direction == Direction.RIGHT) {
                newX += 1;
                if (newX > 6) {
                    newX = 6;
                    turnLeft();
                    continue;
                }
            } else if (direction == Direction.LEFT) {
                newX -= 1;
                if (newX < 0) {
                    newX = 0;
                    turnLeft();
                    continue;
                }
            }
            dieEffect--;
        }
        this.translation = new IntPair(newX, newY);
        return this.translation;
    }


    /**
     * This function aims to let Assam turn left.
     */
    private void turnLeft() {
        switch (direction) {
            case UP -> direction = Direction.LEFT;
            case DOWN -> direction = Direction.RIGHT;
            case RIGHT -> direction = Direction.UP;
            case LEFT -> direction = Direction.DOWN;
        }
    }

    /**
     * This is a getter method for translation.
     * @return translation
     */
    public IntPair getTranslation() {
        return translation;
    }

    /**
     * This is a getter method for direction.
     * @return direction
     */
    public Direction getDirection() {
        return direction;
    }
}
